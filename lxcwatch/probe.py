"""What we run inside each container, and how we read its output.

The probe is plain POSIX sh so it works on Debian, Ubuntu and Alpine
containers alike. It only reads state; the optional package index refresh
(apt-get update / apk update) is the one thing it changes.
"""

import re

from .release import PROBE_DEBIAN

# Processes still running code that an upgrade replaced: their memory maps
# show the old library/binary as "(deleted)". In an LXC (shared host kernel)
# this, not a kernel update, is why you restart after upgrading packages.
STALE_PROCS = r"""for m in /proc/[0-9]*/maps; do grep -qsE '/(usr|lib|lib64|bin|sbin|opt)/[^ ]* \(deleted\)$' "$m" && cat "${m%/maps}/comm" 2>/dev/null; done | sort -u | head -n 20 | tr '\n' ' '"""

PROBE = r"""
REFRESH=__REFRESH__
if [ -r /etc/os-release ]; then . /etc/os-release; fi
echo "os=${PRETTY_NAME:-unknown}"
echo "os_id=${ID:-}"
echo "os_codename=${VERSION_CODENAME:-}"
__DEBIAN__
if [ -f /usr/bin/update ]; then
  n=$(sed -n 's/^export UPDATE_SCRIPT_NAME="\([^"]*\)"$/\1/p' /usr/bin/update | head -n1)
  s=$(sed -n 's/^export SCRIPT_SLUG="\([^"]*\)"$/\1/p' /usr/bin/update | head -n1)
  b=$(sed -n 's/^export COMMUNITY_SCRIPTS_URL="\([^"]*\)"$/\1/p' /usr/bin/update | head -n1)
  if [ -z "$n" ]; then
    u=$(grep -oE 'https?://[^" ]+/ct/[A-Za-z0-9._-]+\.sh' /usr/bin/update | head -n1)
    if [ -n "$u" ]; then n=$(basename "$u" .sh); b=${u%/ct/*}; fi
  fi
  # Some installs/migrations left a full copy of the ct script as
  # /usr/bin/update. It names itself via APP="..." and loads build.func.
  if [ -z "$n" ] && grep -q 'community-scripts' /usr/bin/update && grep -q 'build\.func' /usr/bin/update; then
    a=$(sed -n 's/^APP="\([^"]*\)".*/\1/p' /usr/bin/update | head -n1)
    if [ -n "$a" ]; then
      echo "script_app=$a"
      grep -E 'check_for_(gh|codeberg|gl)_release|^[[:space:]]*(export |local )?[A-Za-z_][A-Za-z0-9_]*=' /usr/bin/update | head -n 300 | sed 's/^/embedded:/'
    fi
  fi
  echo "script=$n"
  echo "slug=$s"
  echo "script_base=$b"
  # Regenerated by community-scripts on every successful install/update.
  echo "update_mtime=$(stat -c %Y /usr/bin/update 2>/dev/null)"
fi
# Names the app goes by, for finding its package (n is reused below).
want="$n $s $(printf %s "${a:-}" | tr -d ' ')"
for f in /root/.* /opt/*_version.txt; do
  [ -f "$f" ] || continue
  case "${f##*/}" in
    .bash*|.profile|.viminfo|.lesshst|.wget-hsts|.selected_editor|.sudo_as_admin_successful|*_history|.gitconfig|.npmrc|.rnd|.hushlogin|.cloud-locale-test.skip|.install-*) continue ;;
  esac
  [ "$(wc -c <"$f")" -le 128 ] || continue
  [ "$(grep -c . "$f")" -le 1 ] || continue
  v=$(head -n1 "$f" | tr -d '\r')
  # Only version-like values: one token containing a digit (1.2.3, v2, a SHA).
  # This skips marker files like the empty ~/.hushlogin the scripts create.
  case "$v" in ''|*[[:space:]]*) continue ;; esac
  case "$v" in *[0-9]*) ;; *) continue ;; esac
  echo "ver:$f=$v"
  echo "vertime:$f=$(stat -c %Y "$f" 2>/dev/null)"
done
# Failure flags community-scripts leave when a script dies inside the
# container (.install-error.failed for an `update` run), with its error capture.
for f in /root/.install-*.failed; do
  [ -f "$f" ] || continue
  n=${f##*/}
  echo "failed:$n=$(head -c 16 "$f" | tr -dc '0-9') $(stat -c %Y "$f" 2>/dev/null)"
  e="${f%.failed}.log.errinfo"
  if [ -f "$e" ]; then head -n 40 "$e" | cut -c1-300 | sed "s|^|errinfo:$n:|"; fi
done
if command -v apt-get >/dev/null 2>&1; then
  echo "pkgmgr=apt"
  # apt-get update exits 0 when only some repos fail, so keep its warnings.
  if [ "$REFRESH" = 1 ]; then
    out=$(apt-get update -qq 2>&1) || echo "pkg_refresh_failed=1"
    printf '%s\n' "$out" | grep -E '^(W|E|Err):' | head -n 20 | cut -c1-600 | sed 's/^/pkgwarn:/'
  fi
  apt-get -s -o Debug::NoLocking=1 dist-upgrade 2>/dev/null | awk '/^Inst /{
    name=$2; old="-"; new=$3
    if ($3 ~ /^\[/) { old=$3; gsub(/\[|\]/, "", old); new=$4 }
    gsub(/[()]/, "", new)
    sec = ($0 ~ /[Ss]ecurity/) ? 1 : 0
    print "pkg:" name " " old " " new " " sec
  }'
  # Apps installed with apt have no ~/.<app> version file. Report installed
  # packages from vendor repos (any whose Release file isn't Debian's or
  # Ubuntu's, so local mirrors still count as the distro), and packages named
  # after the app: "name<TAB>version<TAB>origin or -<TAB>homepage".
  L=/var/lib/apt/lists
  {
    for r in "$L"/*_InRelease "$L"/*_Release; do
      [ -f "$r" ] || continue
      o=$(sed -n 's/^Origin: *//p' "$r" | head -n1)
      case "$o" in Debian|"Debian Backports"|Ubuntu) continue ;; esac
      p=${r%_InRelease}; p=${p%_Release}
      h=${p##*/}
      for f in "$p"_*Packages "$p"_*Packages.*; do
        [ -f "$f" ] || continue
        # Indexes may be stored compressed (Packages.lz4); apt-helper reads any.
        /usr/lib/apt/apt-helper cat-file "$f" 2>/dev/null || cat "$f"
      done | awk -v o="${o:-${h%%_*}}" '/^Package:/ { print $2 "\t" o }'
    done
    echo __DPKG__
    dpkg-query -W -f='${db:Status-Abbrev}\t${Package}\t${Version}\t${Homepage}\n' 2>/dev/null
  } | awk -F'\t' -v want="$want" 'BEGIN { n = split(tolower(want), w, " ") }
    $0 == "__DPKG__" { d = 1; next }
    !d { if (!($1 in tp)) tp[$1] = $2; next }
    $1 !~ /^ii/ { next }
    { m = ($2 in tp)
      for (i = 1; i <= n && !m; i++) if (length(w[i]) >= 3 && index($2, w[i]) == 1) m = 1
      if (m) print "apppkg:" $2 "\t" $3 "\t" (($2 in tp) ? tp[$2] : "-") "\t" $4 }'
elif command -v apk >/dev/null 2>&1; then
  echo "pkgmgr=apk"
  if [ "$REFRESH" = 1 ]; then
    out=$(apk update -q 2>&1) || echo "pkg_refresh_failed=1"
    printf '%s\n' "$out" | grep -E '^(WARNING|ERROR):' | head -n 20 | cut -c1-600 | sed 's/^/pkgwarn:/'
  fi
  apk version -l '<' 2>/dev/null | awk 'NR>1 && NF>=3 { print "pkg:" $1 " - " $3 " 0" }'
else
  echo "pkgmgr=unknown"
fi
if [ -f /var/run/reboot-required ]; then echo "reboot_required=1"; fi
stale=$(__STALE__)
if [ -n "$stale" ]; then echo "stale_procs=$stale"; fi
echo "probe_ok=1"
"""


def probe_script(refresh: bool) -> str:
    return (PROBE.replace("__REFRESH__", "1" if refresh else "0").replace("__STALE__", STALE_PROCS)
            .replace("__DEBIAN__", PROBE_DEBIAN))


# "W: Failed to fetch <url>  <reason>" (apt) and "WARNING: fetching <url>: <reason>" (apk).
FETCH_FAILED_RE = re.compile(r"^(?:W|E|Err):\s*Failed to fetch\s+(\S+)\s*(.*)$|^(?:WARNING|ERROR):\s*(?:fetching\s+)?(https?://\S+?):?\s+(.*)$")


def _reason(text: str) -> str:
    t = text.lower()
    if any(k in t for k in ("signature", "no_pubkey", "expkeysig", "keyexpired", "sqv", "gpg", "is not signed", "untrusted")):
        return "signature check failed"
    if "404" in t or "not found" in t:
        return "not found (404)"
    if "could not resolve" in t or "temporary failure resolving" in t or "dns" in t:
        return "DNS lookup failed"
    if any(k in t for k in ("connect", "timed out", "unreachable", "network error")):
        return "couldn't connect"
    return text.strip()[:120] or "failed"


def refresh_errors(warnings: list[str]) -> list[dict]:
    """Repos whose package lists couldn't be refreshed, from apt/apk warnings."""
    out: dict[str, str] = {}
    for line in warnings:
        m = FETCH_FAILED_RE.match(line)
        if not m:
            continue
        url, rest = (m.group(1), m.group(2)) if m.group(1) else (m.group(3), m.group(4))
        repo = url.split("/dists/", 1)[0] if "/dists/" in url else url.rsplit("/", 1)[0] if url.endswith(("InRelease", "Release", "APKINDEX.tar.gz")) else url
        out.setdefault(repo, _reason(rest))
    return [{"repo": r, "reason": why} for r, why in out.items()]


def parse_probe(text: str) -> dict:
    info: dict = {
        "os": None,
        "os_id": None,
        "script": None,
        "slug": None,
        "script_base": None,
        "versions": {},  # file path -> raw version
        "pkgmgr": None,
        "packages": [],
        "pkg_refresh_failed": False,
        "pkg_warnings": [],  # W:/E: lines from apt-get update (or apk's WARNING/ERROR)
        "pkg_refresh_errors": [],  # [{repo, reason}]
        "reboot_required": False,
        "stale_procs": [],
        "failures": [],  # [{file, code, at, errinfo}]
        "update_mtime": None,
        "os_version": None,
        "os_codename": None,
        "disk_free_kb": None,
        "held": [],
        "usr_unmerged": False,
        "apt_sources": [],  # [{file, line}]
        "script_app": None,  # APP="..." from a ct script embedded as /usr/bin/update
        "embedded": [],  # its release checks and assignments
        "vertimes": {},  # version file path -> mtime
        "app_packages": [],  # [{name, version, origin, homepage}] candidates for apt-installed apps
        "probe_ok": False,
    }
    for line in text.splitlines():
        if line.startswith("ver:"):
            path, _, value = line[4:].partition("=")
            info["versions"][path] = value
        elif line.startswith("aptsrc:"):
            path, _, src = line[7:].partition(":")
            info["apt_sources"].append({"file": path, "line": src.strip()})
        elif line.startswith("pkgwarn:"):
            info["pkg_warnings"].append(line[8:])
        elif line.startswith("apppkg:"):
            name, version, origin, homepage = (line[7:].split("\t") + ["", "", ""])[:4]
            if name and version:
                info["app_packages"].append({"name": name, "version": version,
                                             "origin": None if origin in ("", "-") else origin,
                                             "homepage": homepage or None})
        elif line.startswith("embedded:"):
            info["embedded"].append(line[9:])
        elif line.startswith("vertime:"):
            path, _, value = line[8:].partition("=")
            if value.isdigit():
                info["vertimes"][path] = int(value)
        elif line.startswith("update_mtime="):
            value = line.partition("=")[2]
            info["update_mtime"] = int(value) if value.isdigit() else None
        elif line.startswith("failed:"):
            name, _, rest = line[7:].partition("=")
            code, _, at = rest.partition(" ")
            info["failures"].append({"file": name, "code": int(code) if code.isdigit() else None,
                                     "at": int(at) if at.isdigit() else None, "errinfo": []})
        elif line.startswith("errinfo:"):
            name, _, text = line[8:].partition(":")
            for fail in info["failures"]:
                if fail["file"] == name:
                    fail["errinfo"].append(text)
        elif line.startswith("pkg:"):
            parts = line[4:].split()
            if len(parts) >= 3:
                info["packages"].append({
                    "name": parts[0],
                    "from": None if parts[1] == "-" else parts[1],
                    "to": parts[2],
                    "security": len(parts) > 3 and parts[3] == "1",
                })
        elif "=" in line:
            key, _, value = line.partition("=")
            if key == "stale_procs":
                info["stale_procs"] = value.split()
            elif key == "held":
                info["held"] = value.split()
            elif key == "disk_free_kb":
                info["disk_free_kb"] = int(value) if value.isdigit() else None
            elif key == "usr_unmerged":
                info["usr_unmerged"] = value == "1"
            elif key in ("pkg_refresh_failed", "reboot_required", "probe_ok"):
                info[key] = value == "1"
            elif key in info:
                info[key] = value or None
    info["pkg_refresh_errors"] = refresh_errors(info["pkg_warnings"])
    return info
